"""
core/validators.py
─────────────────────────────────────────────────────────────────────────────
PURPOSE:
    Defines MongoDB $jsonSchema validators for each collection.
    These are applied at the DATABASE LEVEL — MongoDB enforces them,
    not just our Python code.

VIVA POINT:
    "$jsonSchema is MongoDB's built-in validation. Even if a bug in our
    Python code tries to insert an invalid document, MongoDB will reject it.
    This is separate from Django form validation, which happens at the
    application level."

HOW IT WORKS:
    When a collection has a validator, MongoDB checks every insert/update
    against the schema. If the document doesn't match, MongoDB raises
    a WriteError with a clear message.

WHICH COLLECTIONS HAVE VALIDATORS:
    ✅ customers  — full $jsonSchema (required for the academic requirement)
    ✅ payments   — full $jsonSchema (required for the academic requirement)
    ℹ️  orders    — validation done at app level (Django forms)
    ℹ️  credit_profiles — generated by Python, structure guaranteed by code
    ℹ️  risk_alerts     — simple document, app-level validation sufficient
─────────────────────────────────────────────────────────────────────────────
"""


# ── Validator: customers collection ──────────────────────────────────────────

CUSTOMERS_VALIDATOR = {
    "$jsonSchema": {
        "bsonType": "object",
        "title": "Customer Validation",
        "description": "Every document in the customers collection must match this schema.",
        "required": [
            "customer_id",
            "full_name",
            "email",
            "phone",
            "account_created_at",
            "is_active"
        ],
        "properties": {
            "customer_id": {
                "bsonType": "string",
                "pattern": "^CUST-[0-9]{3}$",
                "description": "Must be in the format CUST-NNN (e.g. CUST-001). Required."
            },
            "full_name": {
                "bsonType": "string",
                "minLength": 2,
                "maxLength": 100,
                "description": "Customer's full name. Required. At least 2 characters."
            },
            "email": {
                "bsonType": "string",
                "pattern": "^[^@\\s]+@[^@\\s]+\\.[^@\\s]+$",
                "description": "Valid email address. Required."
            },
            "phone": {
                "bsonType": "string",
                "minLength": 7,
                "maxLength": 20,
                "description": "Phone number as string (allows country codes). Required."
            },
            "date_of_birth": {
                "bsonType": "date",
                "description": "Date of birth. Optional but must be a date if present."
            },
            "account_created_at": {
                "bsonType": "date",
                "description": "When the account was created. Required."
            },
            "address": {
                "bsonType": "object",
                "description": "Embedded address subdocument. Optional.",
                "required": ["city", "state"],
                "properties": {
                    "street":  {"bsonType": "string"},
                    "city":    {"bsonType": "string"},
                    "state":   {"bsonType": "string"},
                    "pincode": {
                        "bsonType": "string",
                        "pattern": "^[0-9]{6}$",
                        "description": "6-digit Indian pincode."
                    }
                }
            },
            "is_active": {
                "bsonType": "bool",
                "description": "Whether the account is active. Required."
            },
            "kyc_verified": {
                "bsonType": "bool",
                "description": "Whether KYC verification is complete. Optional."
            },
            "tags": {
                "bsonType": "array",
                "description": "Array of string tags (e.g. 'premium', 'electronics').",
                "items": {"bsonType": "string"}
            }
        }
    }
}


# ── Validator: payments collection ────────────────────────────────────────────

PAYMENTS_VALIDATOR = {
    "$jsonSchema": {
        "bsonType": "object",
        "title": "Payment Validation",
        "description": "Every document in the payments collection must match this schema.",
        "required": [
            "payment_id",
            "order_id",
            "customer_id",
            "amount_due",
            "amount_paid",
            "status",
            "is_overdue"
        ],
        "properties": {
            "payment_id": {
                "bsonType": "string",
                "description": "Unique payment identifier. Required."
            },
            "order_id": {
                "bsonType": "string",
                "description": "Reference to the related order. Required."
            },
            "customer_id": {
                "bsonType": "string",
                "description": "Reference to the customer. Required."
            },
            "payment_date": {
                "bsonType": ["date", "null"],
                "description": "Date the payment was made. Optional (null if not yet paid)."
            },
            "amount_due": {
                "bsonType": "double",
                "minimum": 0,
                "description": "Total amount due. Required. Must be >= 0."
            },
            "amount_paid": {
                "bsonType": "double",
                "minimum": 0,
                "description": "Amount actually paid so far. Required. Must be >= 0."
            },
            "payment_mode": {
                "bsonType": "string",
                "enum": ["COD", "UPI", "Card", "EMI", "Wallet"],
                "description": "Payment method. Must be one of the allowed values."
            },
            "emi_details": {
                "bsonType": "object",
                "description": "EMI breakdown — only present when payment_mode is EMI.",
                "properties": {
                    "tenure_months":      {"bsonType": "int", "minimum": 1},
                    "installment_number": {"bsonType": "int", "minimum": 1},
                    "next_due_date":      {"bsonType": "date"}
                }
            },
            "status": {
                "bsonType": "string",
                "enum": ["paid", "pending", "overdue", "partial", "waived"],
                "description": "Payment status. Required. Must be one of the allowed values."
            },
            "is_overdue": {
                "bsonType": "bool",
                "description": "Whether this payment is overdue. Required."
            },
            "days_overdue": {
                "bsonType": "int",
                "minimum": 0,
                "description": "Number of days the payment is overdue. 0 if not overdue."
            }
        }
    }
}

